-- 执行位置：fund_db 库内，必须在 02 之后执行
--   psql -v ON_ERROR_STOP=1 -h <HOST> -p <PORT> -U fundmanager -d fund_db -f 03_create_users.sql
-- 执行身份：fundmanager（库 OWNER，推荐）或超级用户；不需要 CREATEROLE。
--   ALTER DEFAULT PRIVILEGES 只对指定 FOR ROLE 账号后续创建的对象生效，
--   02 由 fundmanager 建表，这里显式写了 FOR ROLE fundmanager，谁来跑都一样。
--
-- ⚠️ 前置：3 个分级角色必须已存在（01 第 1b 步创建；已跑过旧版 01 的用 01b 补建）。
--    本脚本不含 CREATE ROLE / ALTER ROLE，因此不会再触发
--    42501 permission denied to create role。
--    若报 role "fund_reader" does not exist，先执行 01b_create_roles.sql 再重跑本文件。
-- ⚠️ PG 14 及以前 public schema 的 owner 是超级用户，fundmanager 执行
--    GRANT USAGE ON SCHEMA public 可能报 permission denied for schema public；
--    此时改用超级用户执行本文件，或让超级用户先执行：
--      GRANT USAGE ON SCHEMA public TO fundmanager WITH GRANT OPTION;
--
-- 权限矩阵（public schema 全部表）
-- | 账号          | SELECT | INSERT | UPDATE | DELETE | DDL | 用途                          |
-- |---------------|--------|--------|--------|--------|-----|-------------------------------|
-- | fundmanager   |   ✓    |   ✓    |   ✓    |   ✓    |  ✓  | Web + Collector + Hangfire    |
-- | fund_reader   |   ✓    |   -    |   -    |   -    |  -  | 报表 / BI / 人工排查           |
-- | fund_inserter |   ✓    |   ✓    |   -    |   -    |  -  | 只灌入数据，不会覆盖历史       |
-- | fund_updater  |   ✓    |   -    |   ✓    |   -    |  -  | 只订正数据，不能新增或删除     |
--
-- 说明：PostgreSQL 的 UPDATE ... WHERE、INSERT ... ON CONFLICT、RETURNING
-- 都要求对涉及的列有 SELECT 权限，因此「新增」「修改」账号必须同时带 SELECT，
-- 只给 INSERT / UPDATE 在实际业务 SQL 上会直接报 permission denied。
-- 这三个账号供外部工具/人工运维使用；应用本身继续使用 01 的 fundmanager。
-- =====================================================================

-- 1) 前置：3 个角色由 01 第 1b 步 / 01b_create_roles.sql 创建（实例级，需 CREATEROLE）
--    本文件从这一步起只做库内授权，fundmanager（库 OWNER）即可执行，
--    不含 CREATE ROLE / ALTER ROLE，不会再触发 42501。
--    执行前可先确认角色齐全（应返回 3 行）：
-- SELECT rolname FROM pg_roles
--  WHERE rolname IN ('fund_reader', 'fund_inserter', 'fund_updater') ORDER BY 1;

-- 2) 库级与 schema 级权限
GRANT CONNECT ON DATABASE fund_db TO fund_reader, fund_inserter, fund_updater;
REVOKE CREATE, TEMPORARY ON DATABASE fund_db FROM fund_reader, fund_inserter, fund_updater;
GRANT USAGE ON SCHEMA public TO fund_reader, fund_inserter, fund_updater;
REVOKE CREATE ON SCHEMA public FROM fund_reader, fund_inserter, fund_updater;

-- PostgreSQL 14 及以前，PUBLIC 默认拥有 public schema 的 CREATE 权限，
-- 上面按角色 REVOKE 无法撤销继承自 PUBLIC 的权限。需要彻底收紧时执行
-- （会影响该库内所有非超级用户，请先确认影响面）：
-- REVOKE CREATE ON SCHEMA public FROM PUBLIC;

-- 3) 现有对象的表/序列权限（02 建好的 26 张表）
GRANT SELECT                ON ALL TABLES    IN SCHEMA public TO fund_reader;
GRANT SELECT, INSERT        ON ALL TABLES    IN SCHEMA public TO fund_inserter;
GRANT SELECT, UPDATE        ON ALL TABLES    IN SCHEMA public TO fund_updater;
-- identity 列（GENERATED BY DEFAULT AS IDENTITY）底层依赖序列，
-- 显式授予 USAGE 以兼容显式写入 Id 或 nextval 的场景。
GRANT USAGE, SELECT         ON ALL SEQUENCES IN SCHEMA public TO fund_inserter, fund_updater;

-- 4) 未来新建对象自动继承（后续 EF 迁移加表时不必重新授权）
ALTER DEFAULT PRIVILEGES FOR ROLE fundmanager IN SCHEMA public
    GRANT SELECT         ON TABLES TO fund_reader;
ALTER DEFAULT PRIVILEGES FOR ROLE fundmanager IN SCHEMA public
    GRANT SELECT, INSERT ON TABLES TO fund_inserter;
ALTER DEFAULT PRIVILEGES FOR ROLE fundmanager IN SCHEMA public
    GRANT SELECT, UPDATE ON TABLES TO fund_updater;
ALTER DEFAULT PRIVILEGES FOR ROLE fundmanager IN SCHEMA public
    GRANT USAGE, SELECT  ON SEQUENCES TO fund_inserter, fund_updater;

